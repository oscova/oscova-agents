// Copies pinned browser dependencies into the Host wwwroot so runtime never loads CDNs.
// Run via: npm run copy-web-vendors
const fs = require("fs");
const path = require("path");

const root = __dirname;
const wwwroot = path.join(root, "wwwroot");
const nodeModules = path.join(root, "node_modules");

function ensureDir(filePath) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function copyFile(source, destination) {
    if (!fs.existsSync(source)) {
        throw new Error(`Required vendor asset was not found: ${source}`);
    }

    ensureDir(destination);
    fs.copyFileSync(source, destination);
    console.log(`Copied ${path.relative(root, destination)}`);
}

function writeFile(destination, content) {
    ensureDir(destination);
    fs.writeFileSync(destination, content, "utf8");
    console.log(`Wrote ${path.relative(root, destination)}`);
}

copyFile(
    path.join(nodeModules, "@tailwindcss", "browser", "dist", "index.global.js"),
    path.join(wwwroot, "lib", "tailwindcss", "browser.global.js"));
copyFile(
    path.join(nodeModules, "@tailwindcss", "browser", "LICENSE"),
    path.join(wwwroot, "lib", "tailwindcss", "LICENSE"));

copyFile(
    path.join(nodeModules, "iconify-icon", "dist", "iconify-icon.min.js"),
    path.join(wwwroot, "lib", "iconify-icon", "iconify-icon.min.js"));
copyFile(
    path.join(nodeModules, "iconify-icon", "license.txt"),
    path.join(wwwroot, "lib", "iconify-icon", "LICENSE"));

const lucideIcons = fs.readFileSync(
    path.join(nodeModules, "@iconify-json", "lucide", "icons.json"),
    "utf8");

writeFile(
    path.join(wwwroot, "lib", "iconify-icon", "lucide-icons.js"),
    `// Generated by copy-web-vendor-assets.js from @iconify-json/lucide.\n` +
    `window.IconifyPreload = window.IconifyPreload || [];\n` +
    `window.IconifyPreload.push(${lucideIcons.trim()});\n`);

writeFile(
    path.join(wwwroot, "lib", "iconify-icon", "offline.js"),
    `// Disable Iconify's API fetch path after local preloaded collections are registered.\n` +
    `customElements.whenDefined("iconify-icon").then(function () {\n` +
    `    var iconifyIcon = customElements.get("iconify-icon");\n` +
    `    if (iconifyIcon && iconifyIcon._api && iconifyIcon._api.setFetch) {\n` +
    `        iconifyIcon._api.setFetch(undefined);\n` +
    `    }\n` +
    `});\n`);

copyFile(
    path.join(nodeModules, "@iconify-json", "lucide", "package.json"),
    path.join(wwwroot, "lib", "iconify-icon", "lucide-package.json"));

copyFile(
    path.join(nodeModules, "apexcharts", "dist", "apexcharts.min.js"),
    path.join(wwwroot, "lib", "apexcharts", "apexcharts.min.js"));
copyFile(
    path.join(nodeModules, "apexcharts", "LICENSE"),
    path.join(wwwroot, "lib", "apexcharts", "LICENSE"));

for (const file of [
    "bundle.min.js",
    "bundle.min.js.LICENSE.txt",
    "silero_vad_legacy.onnx",
    "silero_vad_v5.onnx",
    "vad.worklet.bundle.min.js",
]) {
    copyFile(
        path.join(nodeModules, "@ricky0123", "vad-web", "dist", file),
        path.join(wwwroot, "lib", "vad", file));
}

for (const file of [
    "ort.min.js",
    "ort-wasm-simd-threaded.asyncify.mjs",
    "ort-wasm-simd-threaded.asyncify.wasm",
    "ort-wasm-simd-threaded.jsep.mjs",
    "ort-wasm-simd-threaded.jsep.wasm",
    "ort-wasm-simd-threaded.jspi.mjs",
    "ort-wasm-simd-threaded.jspi.wasm",
    "ort-wasm-simd-threaded.mjs",
    "ort-wasm-simd-threaded.wasm",
]) {
    copyFile(
        path.join(nodeModules, "onnxruntime-web", "dist", file),
        path.join(wwwroot, "lib", "vad", file));
}

// custom-theme-bundle.css declares these variable fonts with @font-face rules pointing at lib/fonts.
for (const font of ["inclusive-sans", "dm-sans", "wix-madefor-text", "ar-one-sans"]) {
    const fontRoot = path.join(nodeModules, "@fontsource-variable", font);
    for (const file of fs.readdirSync(path.join(fontRoot, "files")).filter(name => name.endsWith("-wght-normal.woff2"))) {
        copyFile(
            path.join(fontRoot, "files", file),
            path.join(wwwroot, "lib", "fonts", font, file));
    }

    copyFile(
        path.join(fontRoot, "LICENSE"),
        path.join(wwwroot, "lib", "fonts", font, "LICENSE"));
}

console.log("\nDone. Web vendor assets copied into wwwroot/lib");
